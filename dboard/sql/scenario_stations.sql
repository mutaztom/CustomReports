select tot_office_tab.office_code "Code",tot_office_tab.office_name "Office_Name",tot_office_tab.tot_cif "Total_Cust_Value" ,round(tot_office_tab.tot_cif/tot_value_tab.tot_cif,2) OFFICE_AVG
from
(SELECT ALL AWUNADM.SAD_GENERAL_SEGMENT.IDE_CUO_COD office_code, AWUNADM.SAD_GENERAL_SEGMENT.IDE_CUO_NAM office_name, 
SUM(AWUNADM.SAD_GENERAL_SEGMENT.VGS_CIF) tot_cif
FROM AWUNADM.SAD_GENERAL_SEGMENT
WHERE (AWUNADM.SAD_GENERAL_SEGMENT.IDE_RCP_DAT BETWEEN :date2-3*365 AND :date2
 AND AWUNADM.SAD_GENERAL_SEGMENT.IDE_TYP_PRC=4
 AND AWUNADM.SAD_GENERAL_SEGMENT.IDE_REG_NBR IS NOT NULL
 AND AWUNADM.SAD_GENERAL_SEGMENT.IDE_REG_SER IS NOT NULL
 AND AWUNADM.SAD_GENERAL_SEGMENT.SAD_STA<>'D')
GROUP BY AWUNADM.SAD_GENERAL_SEGMENT.IDE_CUO_COD, 
AWUNADM.SAD_GENERAL_SEGMENT.IDE_CUO_NAM
ORDER BY SUM(AWUNADM.SAD_GENERAL_SEGMENT.VGS_CIF) DESC) tot_office_tab,
(SELECT ALL SUM(AWUNADM.SAD_GENERAL_SEGMENT.VGS_CIF) tot_cif
FROM AWUNADM.SAD_GENERAL_SEGMENT
WHERE (AWUNADM.SAD_GENERAL_SEGMENT.IDE_RCP_DAT BETWEEN :date2-3*365 AND :date2
 AND AWUNADM.SAD_GENERAL_SEGMENT.IDE_TYP_PRC=4
 AND AWUNADM.SAD_GENERAL_SEGMENT.IDE_REG_NBR IS NOT NULL
 AND AWUNADM.SAD_GENERAL_SEGMENT.IDE_REG_SER IS NOT NULL
 AND AWUNADM.SAD_GENERAL_SEGMENT.SAD_STA<>'D')
ORDER BY SUM(AWUNADM.SAD_GENERAL_SEGMENT.VGS_CIF) DESC) tot_value_tab