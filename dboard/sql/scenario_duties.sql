select cust_adt_imd_vat."Year" "year",cust_adt_imd_vat.rate_no "rate",cust_adt_imd_vat."Type" "type" ,
cust_adt_imd_vat.tot_cif "custom_value",col_adt_imd_vat.tot_imd "duty_collected"
from 
(SELECT  
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY') "Year", 
SUM(AWUNADM.GEN_ITEM_N_2.VIT_CIF) tot_cif, TO_NUMBER(NVL((DECODE(AWUNADM.N_UNTARTAB.TAR_T01, 
50, 50, 0.0, 0, AWUNADM.N_UNTARTAB.TAR_T01)), 
0)) rate_no,'IMD' "Type"
FROM AWUNADM.GEN_ITEM_N_2, AWUNADM.N_UNTARTAB
WHERE AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT BETWEEN :date1 AND :date2
 AND  (AWUNADM.GEN_ITEM_N_2.N_H6=AWUNADM.N_UNTARTAB.N_T_H6(+))
GROUP BY TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY'), TO_NUMBER(NVL((DECODE(AWUNADM.N_UNTARTAB.TAR_T01, 
50, 50, 0.0, 0, AWUNADM.N_UNTARTAB.TAR_T01)), 
0))
union
SELECT  
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY') "Year", 
SUM(AWUNADM.GEN_ITEM_N_2.VIT_CIF) tot_cif, TO_NUMBER(NVL(TAR_T03, 
0)) rate_no ,'VAT' "Type"
FROM AWUNADM.GEN_ITEM_N_2, AWUNADM.N_UNTARTAB
WHERE AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT BETWEEN :date1 AND :date2
 AND  (AWUNADM.GEN_ITEM_N_2.N_H6=AWUNADM.N_UNTARTAB.N_T_H6(+))
GROUP BY  TO_NUMBER(NVL(AWUNADM.N_UNTARTAB.TAR_T03,0)),
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY') 
union
SELECT  
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY') "Year", 
SUM(AWUNADM.GEN_ITEM_N_2.VIT_CIF) tot_cif, TO_NUMBER(NVL(TAR_T02, 
0)) rate_no ,'ADT' "Type"
FROM AWUNADM.GEN_ITEM_N_2, AWUNADM.N_UNTARTAB
WHERE AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT BETWEEN :date1 AND :date2
 AND  (AWUNADM.GEN_ITEM_N_2.N_H6=AWUNADM.N_UNTARTAB.N_T_H6(+))
GROUP BY TO_NUMBER(NVL(AWUNADM.N_UNTARTAB.TAR_T02,0)),
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY') 
order by 4,3 ASC) cust_adt_imd_vat,
(SELECT  TO_NUMBER(NVL((DECODE(AWUNADM.N_UNTARTAB.TAR_T01, 50, 50, 0.0, 0, AWUNADM.N_UNTARTAB.TAR_T01)), 0)) rate_no,
'IMD' "Type",TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY') "Year", 
SUM(AWUNADM.SAD_TAX.TAX_LIN_AMT) tot_imd
FROM AWUNADM.GEN_ITEM_N_2, AWUNADM.N_UNTARTAB, AWUNADM.SAD_TAX
WHERE (AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT BETWEEN :date1 AND :date2
 AND AWUNADM.SAD_TAX.TAX_LIN_COD='IMD')
 AND  ((AWUNADM.GEN_ITEM_N_2.N_H6=AWUNADM.N_UNTARTAB.N_T_H6(+))
 AND (AWUNADM.GEN_ITEM_N_2.INSTANCEID=AWUNADM.SAD_TAX.INSTANCEID)
 AND (AWUNADM.GEN_ITEM_N_2.KEY_ITM_NBR=AWUNADM.SAD_TAX.KEY_ITM_NBR))
GROUP BY  
TO_NUMBER(NVL((DECODE(AWUNADM.N_UNTARTAB.TAR_T01, 
50, 50, 0.0, 0, AWUNADM.N_UNTARTAB.TAR_T01)), 
0)), 
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY')
union
SELECT  TO_NUMBER(NVL(TAR_T02, 0)) rate_no,
'ADT' "Type",
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY') "Year", 
SUM(AWUNADM.SAD_TAX.TAX_LIN_AMT) tot_imd
FROM AWUNADM.GEN_ITEM_N_2, AWUNADM.N_UNTARTAB, AWUNADM.SAD_TAX
WHERE (AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT BETWEEN :date1 AND :date2
 AND AWUNADM.SAD_TAX.TAX_LIN_COD='ADT')
 AND  ((AWUNADM.GEN_ITEM_N_2.N_H6=AWUNADM.N_UNTARTAB.N_T_H6(+))
 AND (AWUNADM.GEN_ITEM_N_2.INSTANCEID=AWUNADM.SAD_TAX.INSTANCEID)
 AND (AWUNADM.GEN_ITEM_N_2.KEY_ITM_NBR=AWUNADM.SAD_TAX.KEY_ITM_NBR))
GROUP BY  
TO_NUMBER(NVL(TAR_T02, 0)),TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY')
union
SELECT  TO_NUMBER(NVL(TAR_T03, 0)) rate_no,
'VAT' "Type", 
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY') "Year", 
SUM(AWUNADM.SAD_TAX.TAX_LIN_AMT) tot_imd
FROM AWUNADM.GEN_ITEM_N_2, AWUNADM.N_UNTARTAB, AWUNADM.SAD_TAX
WHERE (AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT BETWEEN :date1 AND :date2
 AND AWUNADM.SAD_TAX.TAX_LIN_COD='VAT')
 AND  ((AWUNADM.GEN_ITEM_N_2.N_H6=AWUNADM.N_UNTARTAB.N_T_H6(+))
 AND (AWUNADM.GEN_ITEM_N_2.INSTANCEID=AWUNADM.SAD_TAX.INSTANCEID)
 AND (AWUNADM.GEN_ITEM_N_2.KEY_ITM_NBR=AWUNADM.SAD_TAX.KEY_ITM_NBR))
GROUP BY  
TO_NUMBER(NVL(TAR_T03, 0)),
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY')
order by 2,1 ASC) col_adt_imd_vat
where cust_adt_imd_vat."Year"=col_adt_imd_vat."Year"(+)
and cust_adt_imd_vat."Type"=col_adt_imd_vat."Type"(+)
and cust_adt_imd_vat.rate_no=col_adt_imd_vat.rate_no(+)
order by 1,3,2 ASC