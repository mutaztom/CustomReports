select ac_ist_imd_adt."Date",ac_ist_imd_adt.tot_est_imd_adt "Estimated_Customs_Duty",
ac_ist_imd_adt.acc_cust_duty "Actual_Customs_Duty",
ac_ist_vat.vat_est_amt "Estimated_VAT",
ac_ist_vat.vat_acc_amt "Actual_VAT_Tax"
from
(select ac_imd_adt.MONTH_YEAR"Date",est_imd_adt.tot_est_imd_adt tot_est_imd_adt,ac_imd_adt.tot_ac_idm_adt acc_cust_duty
from 
(select IMD.MONTH_YEAR MONTH_YEAR,imd.tot_imd+ADT.tot_adt tot_ac_idm_adt
from
(SELECT ALL AWUNADM.GEN_ITEM_N_2.MONTH_YEAR MONTH_YEAR, SUM(AWUNADM.SAD_TAX.TAX_LIN_AMT) tot_imd, 
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'mm') month_no
FROM AWUNADM.GEN_ITEM_N_2, AWUNADM.N_UNTARTAB, AWUNADM.SAD_TAX
WHERE (AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT BETWEEN :date1 AND :date2
 AND AWUNADM.N_UNTARTAB.VALID_TO IS NULL
 AND AWUNADM.SAD_TAX.TAX_LIN_COD='IMD')
 AND  ((AWUNADM.GEN_ITEM_N_2.N_H6=AWUNADM.N_UNTARTAB.N_T_H6(+))
 AND (AWUNADM.GEN_ITEM_N_2.INSTANCEID=AWUNADM.SAD_TAX.INSTANCEID)
 AND (AWUNADM.GEN_ITEM_N_2.KEY_ITM_NBR=AWUNADM.SAD_TAX.KEY_ITM_NBR))
GROUP BY AWUNADM.GEN_ITEM_N_2.MONTH_YEAR, 
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'mm')
ORDER BY TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'mm') ASC) imd,
(SELECT ALL AWUNADM.GEN_ITEM_N_2.MONTH_YEAR MONTH_YEAR, SUM(AWUNADM.SAD_TAX.TAX_LIN_AMT) tot_adt, 
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'mm') month_no
FROM AWUNADM.GEN_ITEM_N_2, AWUNADM.N_UNTARTAB, AWUNADM.SAD_TAX
WHERE (AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT BETWEEN :date1 AND :date2
 AND AWUNADM.N_UNTARTAB.VALID_TO IS NULL
 AND AWUNADM.SAD_TAX.TAX_LIN_COD='ADT')
 AND  ((AWUNADM.GEN_ITEM_N_2.N_H6=AWUNADM.N_UNTARTAB.N_T_H6(+))
 AND (AWUNADM.GEN_ITEM_N_2.INSTANCEID=AWUNADM.SAD_TAX.INSTANCEID)
 AND (AWUNADM.GEN_ITEM_N_2.KEY_ITM_NBR=AWUNADM.SAD_TAX.KEY_ITM_NBR))
GROUP BY AWUNADM.GEN_ITEM_N_2.MONTH_YEAR, 
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'mm')
ORDER BY TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'mm') ASC) ADT
where IMD.MONTH_YEAR=ADT.MONTH_YEAR(+)) ac_imd_adt,
(select est_adt.MONTH_YEAR MONTH_YEAR,Nvl(est_adt.Est_adt,0)+nvl(est_imd.Est_imd,0) tot_est_imd_adt
from 
(SELECT ALL AWUNADM.TAX_LINK.MONTH_YEAR MONTH_YEAR, 
AWUNADM.TAX_LINK.T_AMOUNT Est_adt, AWUNADM.TAX_LINK.TAX_TYPE
FROM AWUNADM.TAX_LINK
WHERE AWUNADM.TAX_LINK.TAX_TYPE='ADT'
AND AWUNADM.TAX_LINK.T_MONTH BETWEEN :date1 AND :date2) est_adt,
(SELECT ALL AWUNADM.TAX_LINK.MONTH_YEAR MONTH_YEAR, 
AWUNADM.TAX_LINK.T_AMOUNT Est_imd, AWUNADM.TAX_LINK.TAX_TYPE
FROM AWUNADM.TAX_LINK
WHERE AWUNADM.TAX_LINK.TAX_TYPE='IMD'
AND AWUNADM.TAX_LINK.T_MONTH BETWEEN :date1 AND :date2) est_imd
where est_imd.MONTH_YEAR=est_adt.MONTH_YEAR(+)) est_imd_adt
where ac_imd_adt.MONTH_YEAR=est_imd_adt.MONTH_YEAR(+)) ac_ist_imd_adt,
(select vat.MONTH_YEAR MONTH_YEAR, vat.tot_VAT vat_acc_amt,est_vat.vat_est_amt vat_est_amt
from
(SELECT ALL AWUNADM.GEN_ITEM_N_2.MONTH_YEAR MONTH_YEAR, SUM(AWUNADM.SAD_TAX.TAX_LIN_AMT) tot_VAT, 
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'mm') month_no
FROM AWUNADM.GEN_ITEM_N_2, AWUNADM.N_UNTARTAB, AWUNADM.SAD_TAX
WHERE (AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT BETWEEN :date1 AND :date2
 AND AWUNADM.N_UNTARTAB.VALID_TO IS NULL
 AND AWUNADM.SAD_TAX.TAX_LIN_COD='VAT')
 AND  ((AWUNADM.GEN_ITEM_N_2.N_H6=AWUNADM.N_UNTARTAB.N_T_H6(+))
 AND (AWUNADM.GEN_ITEM_N_2.INSTANCEID=AWUNADM.SAD_TAX.INSTANCEID)
 AND (AWUNADM.GEN_ITEM_N_2.KEY_ITM_NBR=AWUNADM.SAD_TAX.KEY_ITM_NBR))
GROUP BY AWUNADM.GEN_ITEM_N_2.MONTH_YEAR, 
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'mm')
ORDER BY TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'mm') ASC) vat,
(SELECT ALL AWUNADM.TAX_LINK.MONTH_YEAR MONTH_YEAR, 
AWUNADM.TAX_LINK.T_AMOUNT vat_est_amt, AWUNADM.TAX_LINK.TAX_TYPE
FROM AWUNADM.TAX_LINK
WHERE AWUNADM.TAX_LINK.TAX_TYPE='VAT'
AND AWUNADM.TAX_LINK.T_MONTH BETWEEN :date1 AND :date2) est_vat
where vat.MONTH_YEAR=est_vat.MONTH_YEAR(+)

) ac_ist_vat
where ac_ist_imd_adt."Date"=ac_ist_vat.MONTH_YEAR(+)