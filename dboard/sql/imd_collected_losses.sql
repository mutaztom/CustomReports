select tax.month "Month",tax.year "Year",tax.rate_n "Rate",tax.tot_tax "Collected" ,loss.tot_rel "Losses",tax.month||'-'||tax.rate_n "LookUp"
from
(SELECT ALL TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'mm') month, 
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY') year, 
TO_NUMBER(NVL(DECODE(AWUNADM.N_UNTARTAB.TAR_T01, 50, 40, AWUNADM.N_UNTARTAB.TAR_T01), 
0)) rate_n, 
SUM(AWUNADM.SAD_TAX.TAX_LIN_AMT) tot_tax
FROM AWUNADM.GEN_ITEM_N_2, AWUNADM.N_UNTARTAB, AWUNADM.SAD_TAX
WHERE (AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT BETWEEN :date1 AND :date2
 AND AWUNADM.N_UNTARTAB.VALID_TO IS NULL
 AND AWUNADM.SAD_TAX.TAX_LIN_COD='IMD')
 AND  ((AWUNADM.GEN_ITEM_N_2.N_H6=AWUNADM.N_UNTARTAB.N_T_H6(+))
 AND (AWUNADM.GEN_ITEM_N_2.INSTANCEID=AWUNADM.SAD_TAX.INSTANCEID)
 AND (AWUNADM.GEN_ITEM_N_2.KEY_ITM_NBR=AWUNADM.SAD_TAX.KEY_ITM_NBR))
GROUP BY TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'mm'), 
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY'), TO_NUMBER(NVL(DECODE(AWUNADM.N_UNTARTAB.TAR_T01, 50, 40, AWUNADM.N_UNTARTAB.TAR_T01), 
0))
ORDER BY TO_NUMBER(NVL(DECODE(AWUNADM.N_UNTARTAB.TAR_T01, 50, 40, AWUNADM.N_UNTARTAB.TAR_T01), 
0)) ASC) tax,
(SELECT ALL TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'mm') month, 
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY') year, 
TO_NUMBER(NVL(DECODE(AWUNADM.N_UNTARTAB.TAR_T01, 50, 40, AWUNADM.N_UNTARTAB.TAR_T01), 
0)) rate_n, 
SUM(AWUNADM.SAD_RELIEF.TAX_AMOUNT) tot_rel
FROM AWUNADM.GEN_ITEM_N_2, AWUNADM.N_UNTARTAB, AWUNADM.SAD_RELIEF
WHERE (AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT BETWEEN :date1 AND :date2
 AND AWUNADM.N_UNTARTAB.VALID_TO IS NULL
 AND AWUNADM.SAD_RELIEF.TAX_CODE='IMD')
 AND  ((AWUNADM.GEN_ITEM_N_2.N_H6=AWUNADM.N_UNTARTAB.N_T_H6(+))
 AND (AWUNADM.GEN_ITEM_N_2.INSTANCEID=AWUNADM.SAD_RELIEF.INSTANCEID(+))
 AND (AWUNADM.GEN_ITEM_N_2.KEY_ITM_NBR=AWUNADM.SAD_RELIEF.KEY_ITM_NBR(+)))
GROUP BY TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'mm'), 
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY'), TO_NUMBER(NVL(DECODE(AWUNADM.N_UNTARTAB.TAR_T01, 50, 40, AWUNADM.N_UNTARTAB.TAR_T01), 
0))
ORDER BY TO_NUMBER(NVL(DECODE(AWUNADM.N_UNTARTAB.TAR_T01, 50, 40, AWUNADM.N_UNTARTAB.TAR_T01), 
0)) ASC) loss 
where tax.rate_n=loss.rate_n
and tax.month=loss.month(+)
and tax.year=loss.year(+)
