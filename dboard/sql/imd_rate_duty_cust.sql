select Imd_no_S_W.rate_n rate_n,
Imd_no_S_W.tot_cif+nvl(IMD_S_W.tot_cif,0) tot_cif,
Imd_no_S_W.tot_duty+nvl(IMD_S_W.tot_duty_S_W,0) tot_duty,
Imd_no_S_W.year year
from
(SELECT ALL TO_NUMBER(NVL(DECODE(AWUNADM.N_UNTARTAB.TAR_T01, 50, 40, AWUNADM.N_UNTARTAB.TAR_T01), 
0)) rate_n, 
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY') year, 
SUM(AWUNADM.GEN_ITEM_N_2.VIT_CIF) tot_cif, SUM(0.001*TO_NUMBER(AWUNADM.N_UNTARTAB.TAR_T01)*AWUNADM.GEN_ITEM_N_2.VIT_CIF) tot_duty
FROM AWUNADM.GEN_ITEM_N_2, AWUNADM.N_UNTARTAB, AWUNADM.SAD_TAX
WHERE (AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT BETWEEN :date1 AND :date2
 AND AWUNADM.N_UNTARTAB.VALID_TO IS NULL
 AND AWUNADM.SAD_TAX.TAX_LIN_COD='IMD'
 AND SUBSTR(AWUNADM.GEN_ITEM_N_2.TAR_HSC_NB1, 1, 4) NOT IN ('1701', '1001'))
 AND  ((AWUNADM.GEN_ITEM_N_2.N_H6=AWUNADM.N_UNTARTAB.N_T_H6(+))
 AND (AWUNADM.GEN_ITEM_N_2.INSTANCEID=AWUNADM.SAD_TAX.INSTANCEID)
 AND (AWUNADM.GEN_ITEM_N_2.KEY_ITM_NBR=AWUNADM.SAD_TAX.KEY_ITM_NBR))
GROUP BY TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY'), TO_NUMBER(NVL(DECODE(AWUNADM.N_UNTARTAB.TAR_T01, 50, 40, AWUNADM.N_UNTARTAB.TAR_T01), 
0))
ORDER BY TO_NUMBER(NVL(DECODE(AWUNADM.N_UNTARTAB.TAR_T01, 50, 40, AWUNADM.N_UNTARTAB.TAR_T01), 
0)) ASC) Imd_no_S_W,
(SELECT ALL TO_NUMBER(NVL(DECODE(AWUNADM.N_UNTARTAB.TAR_T01, 
50, 40, 0, 3, 25, 3, AWUNADM.N_UNTARTAB.TAR_T01), 
0)) rate_n, 
TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY') year, 
SUM(AWUNADM.GEN_ITEM_N_2.VIT_CIF) tot_cif, 
SUM(AWUNADM.SAD_TAX.TAX_LIN_BSE*AWUNADM.SAD_TAX.TAX_LIN_RAT) tot_duty_S_W
FROM AWUNADM.GEN_ITEM_N_2, AWUNADM.N_UNTARTAB, AWUNADM.SAD_TAX
WHERE (AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT BETWEEN :date1 AND :date2
 AND AWUNADM.N_UNTARTAB.VALID_TO IS NULL
 AND AWUNADM.SAD_TAX.TAX_LIN_COD='IMD'
 AND SUBSTR(AWUNADM.GEN_ITEM_N_2.TAR_HSC_NB1, 1, 4) IN ('1701', '1001'))
 AND  ((AWUNADM.GEN_ITEM_N_2.N_H6=AWUNADM.N_UNTARTAB.N_T_H6(+))
 AND (AWUNADM.GEN_ITEM_N_2.INSTANCEID=AWUNADM.SAD_TAX.INSTANCEID)
 AND (AWUNADM.GEN_ITEM_N_2.KEY_ITM_NBR=AWUNADM.SAD_TAX.KEY_ITM_NBR))
GROUP BY TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY'), 
TO_NUMBER(NVL(DECODE(AWUNADM.N_UNTARTAB.TAR_T01, 
50, 40, 0, 3, 25, 3, AWUNADM.N_UNTARTAB.TAR_T01), 
0))
ORDER BY TO_NUMBER(NVL(DECODE(AWUNADM.N_UNTARTAB.TAR_T01, 
50, 40, 0, 3, 25, 3, AWUNADM.N_UNTARTAB.TAR_T01), 
0)) ASC) IMD_S_W
where Imd_no_S_W.rate_n=IMD_S_W.rate_n(+)
and Imd_no_S_W.year=IMD_S_W.year(+)
order by 1 ASC