SELECT ALL TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY') YEAR, nvl(AWUNADM.N_COMGRP.COM_GRP,'Others')COM_GRP, 
SUM(AWUNADM.GEN_ITEM_N_2.VIT_CIF) TOT_CIF_SDG
FROM AWUNADM.GEN_ITEM_N_2, AWUNADM.N_UNTARTAB, AWUNADM.N_COMGRP
WHERE (AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT BETWEEN :date1 AND :date2
AND  AWUNADM.N_UNTARTAB.TAR_T02='0'
 AND AWUNADM.N_UNTARTAB.VALID_TO IS NULL)
 AND  ((AWUNADM.GEN_ITEM_N_2.N_H6=AWUNADM.N_UNTARTAB.N_T_H6(+))
 AND (AWUNADM.GEN_ITEM_N_2.N_H6=AWUNADM.N_COMGRP.N_H6_G(+)))
GROUP BY TO_CHAR(AWUNADM.GEN_ITEM_N_2.IDE_RCP_DAT, 'YYYY'), 
nvl(AWUNADM.N_COMGRP.COM_GRP,'Others')