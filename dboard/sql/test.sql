select sum(SAD_GENERAL_SEGMENT.VGS_CIF) Value,
    SAD_GENERAL_SEGMENT.IDE_TYP_PRC Type,
    TRIM(LEADING '0' from TO_CHAR(SAD_GENERAL_SEGMENT.IDE_RCP_DAT, 'mm')) Month from
    AWUNADM.SAD_GENERAL_SEGMENT
    where
	SAD_GENERAL_SEGMENT.IDE_RCP_DAT between :date1 and :date2
	and
    SAD_GENERAL_SEGMENT.IDE_TYP_PRC in ('4', '1')
    group by
    SAD_GENERAL_SEGMENT.IDE_TYP_PRC,
    TRIM(LEADING '0' from TO_CHAR(SAD_GENERAL_SEGMENT.IDE_RCP_DAT, 'mm'))
